using System;
using System.Collections.Generic;
using System.IO;
using UnityEngine;
using Random = UnityEngine.Random;

public enum EbaePricePreset { Lowball, Fair, Greedy }

/// <summary>How the asking price compares to the appraisal (asking / value).</summary>
public enum EbaeGreed { Steal, Fair, Greedy, Delusional }

/// <summary>A buyer's offer on one listing. Lives ~60–90 s of real (unscaled) time.</summary>
[Serializable]
public class EbaeOffer
{
    public string id;
    public string buyer;
    public string message;
    public float amount;        // gross; you get amount × (1 − ebag fee)
    public float lifetime;      // total seconds this offer lives
    public float remaining;     // seconds left, refreshed right before saving
    public bool isJoke;         // "3 dollars and a hug"
    public bool isCounter;      // came back higher after a decline
    public bool isSpecial;      // item-aware buyer (definitelynotdave, ...)

    [NonSerialized] public float expiresAt; // Time.unscaledTime

    public float TimeLeft => Mathf.Max(0f, expiresAt - Time.unscaledTime);
    public float TimeLeft01 => lifetime <= 0f ? 0f : Mathf.Clamp01(TimeLeft / lifetime);
}

/// <summary>An item for sale on ebag plus its live offers.</summary>
[Serializable]
public class EbaeListing
{
    public string id;
    public ItemInstance item;
    public float askingPrice;
    public int dayListed;
    public int offersReceived;
    public List<EbaeOffer> offers = new List<EbaeOffer>();
    public List<string> specialsUsed = new List<string>();

    [NonSerialized] public float nextOfferAt;
    [NonSerialized] public float counterAt;       // 0 = no counter-offer pending
    [NonSerialized] public string counterBuyer;
    [NonSerialized] public float counterAmount;
    /// <summary>Co-op (N5): the host is moving this listing to a neighbour right now; it can't be sold, pawned or delisted.</summary>
    [NonSerialized] public bool neighbourHold;

    public float Appraisal => EbaeMarket.Appraise(item);
    public float Greed => EbaeMarket.GreedOf(item, askingPrice);
    public string ItemName => EbaeMarket.NameOf(item);
    public EbaeOffer BestOffer
    {
        get
        {
            EbaeOffer best = null;
            foreach (var o in offers) if (best == null || o.amount > best.amount) best = o;
            return best;
        }
    }
}

/// <summary>A completed sale (ebag buyer or Pawn Pete).</summary>
[Serializable]
public class EbaeSale
{
    public ItemInstance item;
    public string itemName;
    public Rarity rarity;
    public float price;     // gross
    public float net;       // what landed in GameSession.Cash
    public string buyer;
    public string review;
    public int day;
    public bool pawned;
}

/// <summary>
/// ebag, the online pawn shop: listings, real-time offers, sales and pawning. Local single-player
/// state with its own save file (persistentDataPath/ebae_save.json). Offers are generated by a
/// DontDestroyOnLoad runner (<see cref="EbaeMarketRunner"/>) that bootstraps itself, so buyers keep
/// pinging you in any scene. Greed = asking / appraisal drives how often and how much buyers offer:
/// lowball → near-instant offers at asking, fair → a steady trickle, greedy → few, low, rude offers.
/// </summary>
public static class EbaeMarket
{
    // ---------- tuning (money numbers themselves live in Economy) ----------
    public const float LowballFactor = 0.7f;
    public const float FairFactor = 1.0f;
    public const float GreedyFactor = 1.6f;
    public const int MaxOffersPerListing = 5;
    public const float MinOfferLifetime = 60f;
    public const float MaxOfferLifetime = 90f;
    public const int MaxHistory = 100;
    const float ToastGap = 2.5f;            // coalesce "new offer" toasts closer than this
    const float JokeOfferChance = 0.12f;
    const float WhaleChance = 0.06f;
    const float CounterChance = 0.4f;

    static readonly List<EbaeListing> listings = new List<EbaeListing>();
    static readonly List<EbaeSale> history = new List<EbaeSale>();

    /// <summary>Everything currently for sale (oldest first).</summary>
    public static IReadOnlyList<EbaeListing> Listings => listings;
    /// <summary>Recent sales, oldest first (capped at <see cref="MaxHistory"/>).</summary>
    public static IReadOnlyList<EbaeSale> History => history;
    /// <summary>Lifetime net cash earned on ebag + pawning.</summary>
    public static float TotalEarned { get; private set; }
    public static int TotalSales { get; private set; }
    public static float BestSalePrice { get; private set; }
    public static string BestSaleName { get; private set; }

    /// <summary>Listings / offers / history changed (UI refresh).</summary>
    public static event Action Changed;
    /// <summary>A buyer made an offer (also fired for counter-offers).</summary>
    public static event Action<EbaeListing, EbaeOffer> OfferArrived;
    /// <summary>An offer timed out.</summary>
    public static event Action<EbaeListing, EbaeOffer> OfferExpired;
    /// <summary>Something sold (accepted offer or pawn).</summary>
    public static event Action<EbaeSale> ItemSold;

    public static int PendingOfferCount
    {
        get { int n = 0; foreach (var l in listings) n += l.offers.Count; return n; }
    }

    // ---------- appraisal / pricing ----------

    /// <summary>ebag's market value for an item. Valuables use their rolled value. Anything else in the inventory is a kept
    /// PART and is worth exactly its <see cref="ScrapValue"/>: never more than its bin would have paid.</summary>
    public static float Appraise(ItemInstance item)
    {
        if (item == null) return 0f;
        if (IsPart(item)) return ScrapValue(item);
        if (item.value > 0f) return item.value;
        var def = item.Def;
        if (def != null && def.maxValue > 0f)
            return RoundPrice(Mathf.Lerp(def.minValue, def.maxValue, 0.5f) * Mathf.Clamp(item.condition, 0.1f, 1f));
        return RoundPrice(1f + item.massKg * 2f);
    }

    /// <summary>A kept non-valuable (the KEEP crate takes anything). Parts cannot be listed; Pawn Pete buys them as scrap.</summary>
    public static bool IsPart(ItemInstance item) => item?.Def != null && item.Def.category != ItemCategory.Valuable;

    /// <summary>
    /// THE scrap rule (one rule for ebag, Pawn Pete, the fence and trades): a non-valuable is worth what its correct bin pays
    /// at base rates, with no combo and no contract: recyclables max($0.10, rate x kg), a hazard the flat disposal pay,
    /// junk the compactor's per-kg rate; rounded DOWN to the cent, weight capped at the heaviest the catalog allows, and
    /// whatever value the instance carries ignored. So keeping something can never beat sorting it.
    /// </summary>
    public static float ScrapValue(ItemInstance item)
    {
        var def = item?.Def;
        if (def == null) return 0f;
        if (def.category == ItemCategory.Valuable) return item.value;
        float kg = float.IsNaN(item.massKg) ? 0f : Mathf.Clamp(item.massKg, 0f, def.maxMass);
        float worth = def.category == ItemCategory.Hazard ? Economy.HazardDisposalPay
            : def.category == ItemCategory.Junk ? Economy.CompactorScrapPerKg * kg
            : Mathf.Max(Economy.MinRecyclePayout, Economy.RecycleRatePerKg(def.category) * kg);
        return Mathf.Floor(worth * 100f + 0.001f) / 100f;
    }

    public static float PresetPrice(ItemInstance item, EbaePricePreset preset)
    {
        float f = preset switch
        {
            EbaePricePreset.Lowball => LowballFactor,
            EbaePricePreset.Greedy => GreedyFactor,
            _ => FairFactor
        };
        return Mathf.Max(0.5f, RoundPrice(Appraise(item) * f));
    }

    /// <summary>What Pawn Pete pays right now (no ebag fee): 45% of a treasure's appraisal, or a part's full scrap value.</summary>
    /// <summary>Pawn Pete's instant price. A kept PART pawns for PawnFraction of its scrap (bin) value, rounded down to the
    /// cent: always less than recycling it would have paid.</summary>
    public static float PawnPrice(ItemInstance item) => IsPart(item)
        ? Mathf.Floor(ScrapValue(item) * Economy.PawnFraction * 100f + 0.0001f) / 100f
        : Cents(Appraise(item) * Economy.PawnFraction);

    /// <summary>What you actually get from a sale after ebag's cut (ebae_power_seller lowers it). Docs/Progression.md §6.5.</summary>
    public static float NetAfterFee(float gross) => Cents(gross * (1f - UpgradeEffects.EbaeFee));

    /// <summary>×1.03 on what buyers think your item is worth with the Appraisal Monocle (magnus_vision L2): realised
    /// prices +3% (Docs/Progression.md §6.3), else ×1.</summary>
    public static float MonocleBonus => UpgradeEffects.VisionDetect >= 1f ? 1.03f : 1f;

    /// <summary>Most offers a listing holds at once (+1 buyer with ebag Power Seller).</summary>
    public static int MaxOffers => MaxOffersPerListing + UpgradeEffects.EbaeExtraBuyers;

    public static float GreedOf(ItemInstance item, float asking) => asking / Mathf.Max(0.5f, Appraise(item));

    public static EbaeGreed GreedTier(float greed) =>
        greed < 0.85f ? EbaeGreed.Steal :
        greed < 1.2f ? EbaeGreed.Fair :
        greed < 1.9f ? EbaeGreed.Greedy : EbaeGreed.Delusional;

    public static string GreedLabel(float greed) => GreedTier(greed).ToString().ToUpperInvariant();

    public static string NameOf(ItemInstance item)
    {
        if (item == null) return "???";
        var def = item.Def;
        if (def != null && !string.IsNullOrEmpty(def.name)) return def.name;
        return string.IsNullOrEmpty(item.defId) ? "Mystery Object" : item.defId.Replace('_', ' ');
    }

    /// <summary>Human-looking prices: $0.50 steps under $10, whole dollars under $100, $5 under $1000, else $10.</summary>
    public static float RoundPrice(float v)
    {
        if (v < 10f) return Mathf.Max(0.5f, Mathf.Round(v * 2f) / 2f);
        if (v < 100f) return Mathf.Round(v);
        if (v < 1000f) return Mathf.Round(v / 5f) * 5f;
        return Mathf.Round(v / 10f) * 10f;
    }

    static float Cents(float v) => Mathf.Round(v * 100f) / 100f;

    // ---------- queries ----------

    /// <summary>Find a listing by listing id or by the listed item's uid.</summary>
    public static EbaeListing FindListing(string idOrUid)
    {
        if (string.IsNullOrEmpty(idOrUid)) return null;
        foreach (var l in listings)
            if (l.id == idOrUid || (l.item != null && l.item.uid == idOrUid)) return l;
        return null;
    }

    public static bool FindOffer(string offerId, out EbaeListing listing, out EbaeOffer offer)
    {
        foreach (var l in listings)
            foreach (var o in l.offers)
                if (o.id == offerId) { listing = l; offer = o; return true; }
        listing = null; offer = null;
        return false;
    }

    static ItemInstance FindInventory(string uid)
    {
        if (string.IsNullOrEmpty(uid)) return null;
        foreach (var it in GameSession.Inventory) if (it != null && it.uid == uid) return it;
        return null;
    }

    // ---------- actions ----------

    /// <summary>Move an item from GameSession.Inventory into a new listing. False if it isn't there.</summary>
    public static bool List(string uid, float askingPrice)
    {
        var item = FindInventory(uid);
        if (item == null || item.hot || IsPart(item) || FindListing(uid) != null || IsReservedUid(uid)) return false; // hot goods: fence only; parts: scrap only
        if (float.IsNaN(askingPrice) || float.IsInfinity(askingPrice) || askingPrice < 0.5f ||
            askingPrice > EbaeTradingRules.MaxPriceCents / 100f || listings.Count >= EbaeTradingRules.MaxListingsPerBusiness) return false;
        EnsureBooted();

        var l = new EbaeListing
        {
            id = GameSession.NewUid(),
            item = item,
            askingPrice = Mathf.Max(0.5f, Cents(askingPrice)),
            dayListed = GameSession.Day,
        };
        l.nextOfferAt = Time.unscaledTime + FirstOfferDelay(l.Greed, UpgradeEffects.EbaeOfferSpeed);
        listings.Add(l);
        Save();                                 // listing saved before the item leaves the inventory
        GameSession.RemoveFromInventory(uid);   // (a crash in between duplicates, never loses)
        RaiseChanged();
        return true;
    }

    /// <summary>Take a listing down (by listing id or item uid); the item goes back to the inventory.</summary>
    public static bool Delist(string idOrUid)
    {
        var l = FindListing(idOrUid);
        if (l == null || l.neighbourHold || (EbaeNeighbours.Active && EbaeNeighbours.Instance.IsNpcPending(l.id))) return false;
        listings.Remove(l);
        ReturnToInventory(l.item);
        Save();
        RaiseChanged();
        return true;
    }

    public static bool Accept(string offerId) => Accept(offerId, out _);

    /// <summary>Sell to this offer: listing closes, cash (minus ebag's fee) lands in GameSession.</summary>
    public static bool Accept(string offerId, out EbaeSale sale)
    {
        sale = null;
        if (GameSession.IsGuest) return EbaeNeighbours.UsesHostNpc && EbaeNeighbours.Instance.RequestNpcAccept(offerId);
        if (!FindOffer(offerId, out var l, out var o) || l.neighbourHold || o.TimeLeft <= 0f) return false;
        listings.Remove(l);

        float value = Mathf.Max(0.5f, l.Appraisal);
        bool robbery = o.amount < value * 0.15f;
        sale = new EbaeSale
        {
            item = l.item,
            itemName = l.ItemName,
            rarity = l.item?.Def != null ? l.item.Def.rarity : Rarity.Common,
            price = o.amount,
            net = NetAfterFee(o.amount),
            buyer = o.buyer,
            review = EbaeContent.Pick(o.isJoke || robbery ? EbaeContent.JokeSaleReviews : EbaeContent.Reviews),
            day = GameSession.Day,
            pawned = false,
        };
        RecordSale(sale);
        Ledger.Credit(sale.net, "ebag sale", LedgerIds.Ebae);
        Save();
        try { ItemSold?.Invoke(sale); } catch (Exception e) { Debug.LogException(e); }
        RaiseChanged();
        return true;
    }

    public static bool Decline(string offerId) => Decline(offerId, out _);

    /// <summary>Turn an offer down. Some buyers come back a few seconds later with a better one.
    /// <paramref name="reply"/> is the buyer's parting message.</summary>
    public static bool Decline(string offerId, out string reply)
    {
        reply = null;
        if (GameSession.IsGuest) return EbaeNeighbours.UsesHostNpc && EbaeNeighbours.Instance.RequestNpcDecline(offerId);
        if (!FindOffer(offerId, out var l, out var o) || l.neighbourHold || o.TimeLeft <= 0f) return false;
        reply = DeclineNpcOffer(l, o);
        MarkDirty();
        RaiseChanged();
        return true;
    }

    /// <summary>The same NPC haggling rules on a host-owned guest listing, without touching the host's local market/UI.</summary>
    internal static string DeclineNpcOffer(EbaeListing l, EbaeOffer o)
    {
        string reply;
        l.offers.Remove(o);

        bool counter = !o.isJoke && !o.isCounter && l.counterAt <= 0f
                       && o.amount < l.askingPrice * 0.97f && Random.value < CounterChance;
        if (counter)
        {
            l.counterAt = Time.unscaledTime + Random.Range(2.5f, 5f);
            l.counterBuyer = o.buyer;
            l.counterAmount = Mathf.Min(l.askingPrice, RoundPrice(o.amount * Random.Range(1.08f, 1.25f)));
            reply = EbaeContent.Pick(EbaeContent.CounterTeasers);
        }
        else reply = EbaeContent.Pick(o.isJoke ? EbaeContent.JokeDeclineReplies : EbaeContent.DeclineReplies);

        return reply;
    }

    public static bool PawnNow(string uid) => PawnNow(uid, out _);

    /// <summary>Instant sale to Pawn Pete at Economy.PawnFraction × appraisal (no ebag fee).
    /// Works for inventory items and for listed ones (the listing is pulled).</summary>
    public static bool PawnNow(string uid, out EbaeSale sale)
    {
        sale = null;
        if (FindInventory(uid) is ItemInstance stolen && stolen.hot) return false; // hot goods: fence only
        if (GameSession.IsGuest) return EbaeNeighbours.UsesHostNpc && EbaeNeighbours.Instance.RequestNpcPawn(uid);
        var item = FindInventory(uid);
        var listing = item == null ? FindListing(uid) : null;
        if (item == null && listing == null) return false;
        if (item != null && IsReservedUid(uid)) return false;
        if (listing != null && listing.neighbourHold) return false;
        if (listing != null) { item = listing.item; listings.Remove(listing); }

        // A part is scrapped, not sold: Pete pays its bin value and it is no sale (no history, no stats, no Work Order credit).
        bool scrap = IsPart(item);
        float price = PawnPrice(item);
        sale = new EbaeSale
        {
            item = item,
            itemName = NameOf(item),
            rarity = item?.Def != null ? item.Def.rarity : Rarity.Common,
            price = price,
            net = price,
            buyer = EbaeContent.PawnBuyer,
            review = EbaeContent.Pick(EbaeContent.PawnReviews),
            day = GameSession.Day,
            pawned = true,
        };
        if (!scrap) RecordSale(sale);
        Save();
        if (listing == null) GameSession.RemoveFromInventory(uid);
        if (price > 0f) Ledger.Credit(price, scrap ? "scrap" : "pawn", LedgerIds.Pawn);
        if (!scrap) try { ItemSold?.Invoke(sale); } catch (Exception e) { Debug.LogException(e); }
        RaiseChanged();
        return true;
    }

    static void RecordSale(EbaeSale sale)
    {
        history.Add(sale);
        if (history.Count > MaxHistory) history.RemoveRange(0, history.Count - MaxHistory);
        TotalEarned += sale.net;
        TotalSales++;
        if (sale.price > BestSalePrice) { BestSalePrice = sale.price; BestSaleName = sale.itemName; }
    }

    /// <summary>Put an item back in the inventory without counting it as a new treasure find.</summary>
    static void ReturnToInventory(ItemInstance item)
    {
        if (item == null || FindInventory(item.uid) != null) return;
        // GameSession.AddToInventory would bump TotalTreasuresFound, so add directly.
        GameSession.Inventory.Add(item);
        GameSession.NotifyChanged();
        if (Application.isPlaying) GameSession.Save(); // Save() writes unconditionally; never from edit mode
    }

    // ---------- neighbours (co-op ebag, Docs/Multiplayer.md §13.8, package N5) ----------

    /// <summary>Set by <c>EbaeNeighbours</c> while in a Town: an inventory item offered in a pending neighbour trade (it can't be
    /// listed or pawned until the offer ends). Null outside a session.</summary>
    public static Func<string, bool> IsReserved;

    public static bool IsReservedUid(string uid)
    {
        if (string.IsNullOrEmpty(uid) || IsReserved == null) return false;
        try { return IsReserved(uid); }
        catch (Exception e) { Debug.LogException(e); return false; }
    }

    /// <summary>Find a listing by its listing id only (neighbour trades name listings by id).</summary>
    public static EbaeListing FindListingById(string id)
    {
        if (string.IsNullOrEmpty(id)) return null;
        foreach (var l in listings) if (l.id == id) return l;
        return null;
    }

    /// <summary>
    /// The host settled a neighbour's purchase of listing <paramref name="listingId"/> (the cash already moved through the
    /// Ledger on the host): the listing closes, the sale is recorded and a traded item (if any) lands in the inventory.
    /// </summary>
    public static bool CompleteNeighbourSale(string listingId, string buyer, float price, float net, ItemInstance tradeItem, out EbaeSale sale)
    {
        sale = null;
        var l = FindListingById(listingId);
        if (l == null) { if (tradeItem != null) ReceiveItem(tradeItem); return false; }
        listings.Remove(l);
        sale = new EbaeSale
        {
            item = l.item,
            itemName = l.ItemName,
            rarity = l.item?.Def != null ? l.item.Def.rarity : Rarity.Common,
            price = price,
            net = net,
            buyer = buyer,
            review = tradeItem != null ? $"traded for {NameOf(tradeItem)}" + (price > 0f ? $" + {Economy.Money(price)}" : "") + ". neighbourly."
                                       : "bought by a neighbour. they live like 20 m away.",
            day = GameSession.Day,
            pawned = false,
        };
        RecordSale(sale);
        if (tradeItem != null) ReceiveItem(tradeItem);
        Save();
        try { ItemSold?.Invoke(sale); } catch (Exception e) { Debug.LogException(e); }
        RaiseChanged();
        return true;
    }

    /// <summary>An item bought or traded from a neighbour goes into the inventory (keep crate), not counted as a new find.</summary>
    public static void ReceiveItem(ItemInstance item)
    {
        if (item == null) return;
        ReturnToInventory(item);
        RaiseChanged();
    }

    /// <summary>Tell the UI something about listings or reservations changed.</summary>
    public static void Notify() => RaiseChanged();

    /// <summary>Retain rejected legacy listings and let their owner correct the asking price.</summary>
    public static bool Reprice(string listingId, float price)
    {
        var l = FindListingById(listingId);
        if (l == null || l.neighbourHold || float.IsNaN(price) || float.IsInfinity(price) || price < 0.5f ||
            price > EbaeTradingRules.MaxPriceCents / 100f || (EbaeNeighbours.Active && EbaeNeighbours.Instance.IsNpcPending(l.id))) return false;
        l.askingPrice = Cents(price);
        l.offers.Clear();
        l.counterAt = 0f;
        l.nextOfferAt = Time.unscaledTime + FirstOfferDelay(l.Greed, UpgradeEffects.EbaeOfferSpeed);
        Save();
        RaiseChanged();
        return true;
    }

    internal static void ApplyNpcOffers(string listingId, List<EbaeOffer> incoming, int received)
    {
        var l = FindListingById(listingId);
        if (l == null || l.neighbourHold) return;
        var old = new HashSet<string>();
        foreach (var o in l.offers) old.Add(o.id);
        l.offers.Clear();
        foreach (var o in incoming)
        {
            if (o.remaining <= 0f) continue;
            o.expiresAt = Time.unscaledTime + o.remaining;
            l.offers.Add(o);
            if (!old.Contains(o.id)) { Raise(OfferArrived, l, o); NotifyClosedLaptop(l, o); }
        }
        l.offersReceived = received;
        MarkDirty();
        RaiseChanged();
    }

    /// <summary>Only after a host-confirmed NPC sale. Cash is already authoritative; never send a second ledger credit.</summary>
    internal static bool CompleteNpcSale(string listingId, string uid, string buyer, float price, float net, bool pawned, out EbaeSale sale)
    {
        sale = null;
        var l = FindListingById(listingId);
        var item = l != null ? l.item : FindInventory(uid);
        if (item == null || item.uid != uid) return false;
        if (l != null) listings.Remove(l);
        else GameSession.RemoveFromInventory(uid);
        sale = new EbaeSale {
            item = item, itemName = NameOf(item), rarity = item.Def != null ? item.Def.rarity : Rarity.Common,
            price = price, net = net, buyer = buyer, pawned = pawned, day = GameSession.Day,
            review = pawned ? "Pawn Pete paid up. no refunds." : "paid promptly. would buy more rubbish."
        };
        bool scrap = pawned && IsPart(item); // a part scrapped through the host: not a sale
        if (!scrap) RecordSale(sale);
        Save();
        if (!scrap) try { ItemSold?.Invoke(sale); } catch (Exception e) { Debug.LogException(e); }
        RaiseChanged();
        return true;
    }

    /// <summary>A neighbour trade is over: release every hold this machine had (session ended mid-trade).</summary>
    public static void ClearNeighbourHolds()
    {
        bool any = false;
        foreach (var l in listings) if (l.neighbourHold) { l.neighbourHold = false; any = true; }
        if (any) RaiseChanged();
    }

    // ---------- offer simulation ----------

    // ebag Bulk Lister Pro (power seller L2+): offers arrive EbaeOfferSpeed× faster
    internal static float FirstOfferDelay(float greed, float speed = 1f) => (GreedTier(greed) switch
    {
        EbaeGreed.Steal => Random.Range(1.2f, 3f),
        EbaeGreed.Fair => Random.Range(5f, 10f),
        EbaeGreed.Greedy => Random.Range(12f, 22f),
        _ => Random.Range(20f, 35f),
    }) / Mathf.Max(1f, speed);

    internal static float NextOfferInterval(float greed, float speed = 1f) => (GreedTier(greed) switch
    {
        EbaeGreed.Steal => Random.Range(3f, 6f),
        EbaeGreed.Fair => Random.Range(9f, 16f),
        EbaeGreed.Greedy => Random.Range(20f, 35f) * Mathf.Clamp(greed / 1.2f, 1f, 1.6f),
        _ => Random.Range(35f, 60f),
    }) / Mathf.Max(1f, speed);

    static float lastToastAt = -999f;
    static int toastBacklog;

    /// <summary>Advance offers (called every frame by the runner).</summary>
    internal static void Tick()
    {
        float now = Time.unscaledTime;
        bool changed = false;

        for (int li = listings.Count - 1; li >= 0; li--)
        {
            var l = listings[li];

            for (int i = l.offers.Count - 1; i >= 0; i--)
            {
                var o = l.offers[i];
                if (now < o.expiresAt) continue;
                l.offers.RemoveAt(i);
                changed = true;
                Raise(OfferExpired, l, o);
            }

            if (l.counterAt > 0f && now >= l.counterAt)
            {
                var c = NewOffer(l.counterBuyer, EbaeContent.Format(EbaeContent.Pick(EbaeContent.Counters), l.counterAmount, l.ItemName, l.item?.foundAt), l.counterAmount);
                c.isCounter = true;
                l.counterAt = 0f;
                Deliver(l, c);
                QueueAutoAccept(l, c);
                changed = true;
            }

            if (now >= l.nextOfferAt)
            {
                if (l.offers.Count < MaxOffers)
                {
                    var o = MakeOffer(l, MonocleBonus);
                    Deliver(l, o);
                    QueueAutoAccept(l, o);
                    // ebag Power Seller: one more buyer per listing shows up with the first offer
                    if (UpgradeEffects.EbaeExtraBuyers > 0 && l.offersReceived == 1 && l.offers.Count < MaxOffers)
                    {
                        var extra = MakeOffer(l, MonocleBonus);
                        Deliver(l, extra);
                        QueueAutoAccept(l, extra);
                    }
                    changed = true;
                }
                l.nextOfferAt = now + NextOfferInterval(l.Greed, UpgradeEffects.EbaeOfferSpeed);
            }
        }

        // ebag Diamond Seller (power seller L3): sell to any offer at ≥ 97% of appraisal, after the loop
        if (autoAccept.Count > 0)
        {
            foreach (var id in autoAccept)
                if (Accept(id, out var sold) && sold != null)
                {
                    GameHUD.Toast($"ebag Diamond Seller auto-sold your {sold.itemName} for {Economy.Money(sold.price)}!", ToastStyle.Rare, 3.5f);
                    Sfx.Play("cash");
                }
            autoAccept.Clear();
            changed = true;
        }

        if (toastBacklog > 0 && now - lastToastAt >= ToastGap && !EbaeUI.IsOpen && PlayerController.Local != null)
        {
            GameHUD.Toast(toastBacklog == 1 ? "ebag: another offer is waiting on the laptop!" : $"ebag: {toastBacklog} more offers waiting on the laptop!", ToastStyle.Good);
            Sfx.Play("notify");
            toastBacklog = 0;
            lastToastAt = now;
        }
        if (EbaeUI.IsOpen) toastBacklog = 0;

        if (changed) { MarkDirty(); RaiseChanged(); }
    }

    static readonly List<string> autoAccept = new List<string>();

    static void QueueAutoAccept(EbaeListing l, EbaeOffer o)
    {
        float at = UpgradeEffects.EbaeAutoAccept;
        if (at <= 0f || o == null || o.isJoke || l == null) return;
        if (o.amount + 0.001f >= Mathf.Max(0.5f, l.Appraisal) * at && !autoAccept.Contains(o.id)) autoAccept.Add(o.id);
    }

    static void Deliver(EbaeListing l, EbaeOffer o)
    {
        l.offers.Add(o);
        l.offersReceived++;
        Raise(OfferArrived, l, o);
        NotifyClosedLaptop(l, o);
    }

    static void NotifyClosedLaptop(EbaeListing l, EbaeOffer o)
    {
        if (EbaeUI.IsOpen) return;                  // the open UI does its own in-window pings
        if (PlayerController.Local == null) return; // menus / loading: offers still arrive, quietly
        float now = Time.unscaledTime;
        if (now - lastToastAt < ToastGap) { toastBacklog++; return; }
        lastToastAt = now;

        bool full = o.amount >= l.askingPrice - 0.001f;
        string text = o.isJoke ? $"ebag: {o.buyer} offered {Economy.Money(o.amount)} for your {l.ItemName}. lol."
                    : full ? $"ebag: FULL PRICE offer for {l.ItemName}! ({Economy.Money(o.amount)})"
                    : $"ebag: {Economy.Money(o.amount)} offer for {l.ItemName}!";
        GameHUD.Toast(text, o.isSpecial || full ? ToastStyle.Rare : ToastStyle.Good);
        Sfx.Play("notify");
    }

    static EbaeOffer NewOffer(string buyer, string message, float amount)
    {
        float life = Random.Range(MinOfferLifetime, MaxOfferLifetime);
        return new EbaeOffer
        {
            id = GameSession.NewUid(),
            buyer = buyer,
            message = message,
            amount = Mathf.Clamp(Cents(amount), 0.5f, EbaeTradingRules.MaxPriceCents / 100f),
            lifetime = life,
            remaining = life,
            expiresAt = Time.unscaledTime + life,
        };
    }

    /// <summary>Roll one buyer's offer for a listing.</summary>
    internal static EbaeOffer MakeOffer(EbaeListing l, float monocle = 1f)
    {
        float value = Mathf.Max(0.5f, l.Appraisal) * monocle;
        float asking = l.askingPrice;
        float greed = asking / value;
        var tier = GreedTier(greed);
        string itemName = l.ItemName, where = l.item?.foundAt;

        // 1) Item-aware weirdo (more likely to be the first to show up).
        var specials = EbaeContent.MatchingSpecials(l.item, l.specialsUsed);
        if (specials.Count > 0 && Random.value < (l.offersReceived == 0 ? 0.65f : 0.3f))
        {
            var s = specials[Random.Range(0, specials.Count)];
            l.specialsUsed.Add(s.buyer);
            float amt = Mathf.Min(asking, RoundPrice(value * s.valueMult * Random.Range(0.95f, 1.05f)));
            var so = NewOffer(s.buyer, EbaeContent.Format(s.message, amt, itemName, where), amt);
            so.isSpecial = true;
            return so;
        }

        // 2) Joke lowball ("will u take 3 dollars and a hug").
        if (Random.value < JokeOfferChance)
        {
            var j = EbaeContent.JokeOffers[Random.Range(0, EbaeContent.JokeOffers.Length)];
            if (asking >= j.amount * 3f)
            {
                var jo = NewOffer(RandomBuyer(l), j.message, j.amount);
                jo.isJoke = true;
                return jo;
            }
        }

        // 3) A normal buyer with their own idea of what it's worth.
        string buyer = RandomBuyer(l);
        float willing = value * Random.Range(0.65f, 1.15f);
        if (Random.value < WhaleChance) willing = value * Random.Range(1.25f, 1.7f);

        if (tier == EbaeGreed.Steal)
        {
            // Priced under value: everyone pays asking, some fight over it.
            if (Random.value < 0.15f && asking * 1.08f < value)
            {
                float over = RoundPrice(Mathf.Min(value, asking * Random.Range(1.05f, 1.2f)));
                return NewOffer(buyer, "i'll pay MORE than asking so nobody else gets it. " + Economy.Money(over), over);
            }
            return NewOffer(buyer, EbaeContent.Pick(EbaeContent.AtAsking), asking);
        }

        if (willing >= asking) return NewOffer(buyer, EbaeContent.Pick(EbaeContent.AtAsking), asking);

        float amount = RoundPrice(willing * Random.Range(0.8f, 1f));
        if (tier >= EbaeGreed.Greedy) amount = RoundPrice(amount * Random.Range(0.75f, 0.95f)); // offended buyers lowball harder
        if (amount >= asking) return NewOffer(buyer, EbaeContent.Pick(EbaeContent.AtAsking), asking);

        string[] pool = tier >= EbaeGreed.Greedy && Random.value < 0.6f ? EbaeContent.GreedyCallouts : EbaeContent.Haggles;
        return NewOffer(buyer, EbaeContent.Format(EbaeContent.Pick(pool), amount, itemName, where), amount);
    }

    static string RandomBuyer(EbaeListing l)
    {
        string pick = EbaeContent.Pick(EbaeContent.Buyers);
        for (int tries = 0; tries < 6; tries++)
        {
            bool taken = false;
            foreach (var o in l.offers) if (o.buyer == pick) { taken = true; break; }
            if (!taken) break;
            pick = EbaeContent.Pick(EbaeContent.Buyers);
        }
        return pick;
    }

    internal static EbaeOffer MakeCounterOffer(EbaeListing l)
    {
        var o = NewOffer(l.counterBuyer, EbaeContent.Format(EbaeContent.Pick(EbaeContent.Counters), l.counterAmount, l.ItemName, l.item?.foundAt), l.counterAmount);
        o.isCounter = true;
        l.counterAt = 0f;
        return o;
    }

