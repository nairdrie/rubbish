    [Serializable]
    class SaveData
    {
        public List<EbaeListing> listings = new List<EbaeListing>();
        public List<EbaeSale> history = new List<EbaeSale>();
        public float totalEarned;
        public int totalSales;
        public float bestSalePrice;
        public string bestSaleName;

        // Hotfix L0: the same gen as rubbish_save.json on every save, so recovery picks a matching pair.
        public long gen;
    }

    /// <summary>Loaded cleanly (hotfix L0); <c>booted</c> = Load has run, so a blocked load isn't retried every call.</summary>
    static bool loaded, booted;
    static bool dirty;

    /// <summary>Queue a save for the end of the frame (the runner flushes it).</summary>
    static void MarkDirty() => dirty = true;

    internal static void FlushIfDirty()
    {
        if (dirty) Save();
    }

    public static void Save()
    {
        dirty = false;
        if (!loaded) return;
        LegacySave.WriteBoth(false); // both legacy files, same gen, at most one write per 2 s, refused while SaveGuard is latched (L0)
    }

    /// <summary>The ebag half of the save; LegacySave writes it beside GameSession's under the same <paramref name="gen"/>.</summary>
    internal static string BuildSaveJson(long gen)
    {
        foreach (var l in listings)
            foreach (var o in l.offers) o.remaining = o.TimeLeft;
        var d = new SaveData
        {
            listings = new List<EbaeListing>(listings),
            history = new List<EbaeSale>(history),
            totalEarned = TotalEarned,
            totalSales = TotalSales,
            bestSalePrice = BestSalePrice,
            bestSaleName = BestSaleName,
        };
        d.gen = gen;
        return JsonUtility.ToJson(d, true);
    }

    internal static bool SaveJsonParses(string json)
    {
        try { return JsonUtility.FromJson<SaveData>(json) != null; }
        catch (Exception) { return false; }
    }

    /// <summary>
    /// Load (hotfix L0): resolved together with rubbish_save.json (same gen). <c>loaded</c> only after a good parse, a
    /// recovered backup or a missing file; an unreadable file is kept as *.corrupt-*.json and saving stays off.
    /// </summary>
    public static void Load()
    {
        booted = true;
        listings.Clear(); history.Clear();
        TotalEarned = 0f; TotalSales = 0; BestSalePrice = 0f; BestSaleName = null;
        loaded = LegacySave.Load(LegacySave.Part.Ebae, ApplySaveJson);
        Reconcile();
        RaiseChanged();
    }

    /// <summary>
    /// Co-op (Docs/Multiplayer.md §13, N1; BusinessSlots): replace the listings with another of the player's businesses'
    /// ebag JSON (what <see cref="BuildSaveJson"/> writes; null/empty = a new business with none). Never saves by itself.
    /// </summary>
    internal static void LoadBusinessJson(string json)
    {
        booted = true;
        listings.Clear(); history.Clear();
        TotalEarned = 0f; TotalSales = 0; BestSalePrice = 0f; BestSaleName = null;
        if (!string.IsNullOrEmpty(json)) ApplySaveJson(json);
        Reconcile();
        RaiseChanged();
    }

    static void ApplySaveJson(string json)
    {
        var d = JsonUtility.FromJson<SaveData>(json);
        if (d == null) throw new FormatException("ebae_save.json is not an ebag save");
        float now = Time.unscaledTime;
        if (d.listings != null)
            foreach (var l in d.listings)
            {
                if (l == null || l.item == null) continue;
                l.offers ??= new List<EbaeOffer>();
                l.specialsUsed ??= new List<string>();
                l.offers.RemoveAll(o => o == null || o.remaining <= 0.5f);
                foreach (var o in l.offers) o.expiresAt = now + Mathf.Min(o.remaining, Mathf.Max(o.lifetime, 1f));
                l.nextOfferAt = now + Random.Range(2f, 6f); // "while you were away..."
                listings.Add(l);
            }
        if (d.history != null) history.AddRange(d.history.FindAll(s => s != null));
        TotalEarned = d.totalEarned;
        TotalSales = d.totalSales;
        BestSalePrice = d.bestSalePrice;
        BestSaleName = d.bestSaleName;
    }

    /// <summary>An item can't be both listed and in the inventory (e.g. after a crash mid-save):
    /// the listing wins.</summary>
    static void Reconcile()
    {
        foreach (var l in listings)
            if (l.item != null && FindInventory(l.item.uid) != null)
                GameSession.RemoveFromInventory(l.item.uid);
    }

    /// <summary>Wipe ebag (debug / new game). GameSession.ResetAll doesn't know about ebag.</summary>
    public static void ResetAll(bool deleteSave)
    {
        // Hotfix L0: a "delete" rewrites the file with the reset state (the old one stays in the generations), and is refused
        // entirely while SaveGuard is latched or the save didn't load cleanly.
        if (deleteSave && !LegacySave.MayReset("EbaeMarket.ResetAll(true)")) return;
        listings.Clear(); history.Clear();
        TotalEarned = 0f; TotalSales = 0; BestSalePrice = 0f; BestSaleName = null;
        toastBacklog = 0;
        if (deleteSave) LegacySave.WriteChangeNow("EbaeMarket.ResetAll(true)");
        else Save();
        RaiseChanged();
    }

    static void RaiseChanged()
    {
        try { Changed?.Invoke(); }
        catch (Exception e) { Debug.LogException(e); }
    }

    // A throwing subscriber must never stall the offer loop halfway through a tick.
    static void Raise(Action<EbaeListing, EbaeOffer> evt, EbaeListing l, EbaeOffer o)
    {
        try { evt?.Invoke(l, o); }
        catch (Exception e) { Debug.LogException(e); }
    }

    // ---------- bootstrap ----------

    static EbaeMarketRunner runner;

    static void EnsureBooted()
    {
        if (!Application.isPlaying) return;
        if (!booted) Load();
        if (runner == null)
        {
            var go = new GameObject("[ebag Market]");
            UnityEngine.Object.DontDestroyOnLoad(go);
            runner = go.AddComponent<EbaeMarketRunner>();
        }
    }

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.BeforeSceneLoad)]
    static void Boot() => EnsureBooted(); // after GameSession has loaded (SubsystemRegistration)

    // Statics survive play sessions when domain reload is disabled; start clean each play session.
    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
    static void ResetStatics()
    {
        Changed = null; OfferArrived = null; OfferExpired = null; ItemSold = null;
        listings.Clear(); history.Clear();
        TotalEarned = 0f; TotalSales = 0; BestSalePrice = 0f; BestSaleName = null;
        loaded = booted = false; dirty = false; runner = null;
        lastToastAt = -999f; toastBacklog = 0;
        autoAccept.Clear();
        IsReserved = null;
    }
