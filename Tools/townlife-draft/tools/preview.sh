#!/bin/bash
# TownLife preview: build the current DRAFT TownLife sources into the live town IN MEMORY and photograph it.
# No recompile, no domain reload, nothing imported into Assets, nothing saved, scenes left clean.
#
#   preview.sh <modules-csv|all> <absolute-out-dir> [shots-csv|all] [options]
#
#   modules : all | csv of  paint,park,meadows,streets,yards,edges  plus preview-only  fences,smoke
#             everything = fences + the six real modules (the whole town as it will look)
#             none       = build nothing: photograph the scene exactly as it is (after integration: the real result)
#   out-dir : absolute, outside the Unity project. Receives <shot>.png, shots.tsv, report.txt, result.txt, cli.txt,
#             compile.txt
#   shots   : all (34 fixed + custom) | csv of shot names            (default: all)
#   options : "key=value;key=value"  (see TownLifePreview.Run): shotsFile=<abs>, districts=acres+meadows,
#             hideFences=0|1, hidePark=0|1, parkKeep=a,b, hideLive=0|1 (integrated TownLife objects already in the
#             scene; default 1 whenever a real module is built), hide=a,b, noScene=1, size=WxH, anything else -> ctx.options
#   report.txt ends with a per-module table (objects, GameObjects, ms); result.txt repeats it as "module <name>: ..." lines.
#   env     : PREVIEW_OWNER=<unique agent name> (lock owner; default preview-<pid>), PREVIEW_DRAFT=<draft root>
#
# How: tools/compile.sh compiles the draft TownLife*.cs files (offline, Unity's csc) into a uniquely named scratch DLL
# that references the Editor's loaded game assemblies; one eval_file then loads it with Assembly.Load(bytes, pdb) and
# invokes TownLifePreview.Run by reflection. A fresh assembly name per run means no duplicate-type clashes, also after
# the TownLife files are integrated into Assembly-CSharp-Editor.
# Exit: 0 = OK, 3 = photos made but a module reported errors, 1 = failed, 2 = usage / compile error, 4 = editor busy.
set -u
P=/Users/nick/Dev/Rubbish
HERE="$(cd "$(dirname "$0")" && pwd)"; SP="$(cd "$HERE/.." && pwd)"
LOCK="$SP/editor.lock"; ME="${PREVIEW_OWNER:-preview-$$}"
USAGE="usage: preview.sh <modules-csv|all> <absolute-out-dir> [shots-csv|all] [options]"
MODULES="${1:?$USAGE}"; OUT="${2:?$USAGE}"; SHOTS="${3:-all}"; OPTIONS="${4:-}"
case "$OUT" in /*) ;; *) echo "preview.sh: out dir must be absolute" >&2; exit 2;; esac
case "$OUT" in "$P"|"$P"/*) echo "preview.sh: refusing to write inside the Unity project" >&2; exit 2;; esac
mkdir -p "$OUT"; OUT="$(cd "$OUT" && pwd)"
T0=$(date +%s)

# ---- 1. offline compile (no Editor contact, no lock needed)
CLOG="$OUT/compile.txt"
if [ -n "${PREVIEW_DRAFT:-}" ]; then "$HERE/compile.sh" --quiet --draft "$PREVIEW_DRAFT" > "$CLOG" 2>&1; else "$HERE/compile.sh" --quiet > "$CLOG" 2>&1; fi
CRC=$?
# the preview only needs the TownLife-only pass; errors in the full editor pass are shown but do not block photos
if grep -q '^\[townlife\].*error ' "$CLOG" || ! grep -q '^DLL: ' "$CLOG"; then cat "$CLOG"; echo "preview.sh: compile failed, nothing was run in the Editor" >&2; exit 2; fi
if [ $CRC -ne 0 ]; then grep '^\[editor\]' "$CLOG" | head -20; echo "preview.sh: WARNING the full editor-assembly pass has errors (continuing: the TownLife-only pass is clean)"; fi
DLL=$(sed -n 's/^DLL: //p' "$CLOG"); PDB=$(sed -n 's/^PDB: //p' "$CLOG")
[ -s "$DLL" ] || { cat "$CLOG"; echo "preview.sh: no DLL produced" >&2; exit 2; }
T1=$(date +%s)

# ---- 2. the eval that loads the DLL and calls TownLifePreview.Run
EVAL="$(dirname "$DLL")/preview_eval.cs"
DLL="$DLL" PDB="$PDB" MODULES="$MODULES" OUT="$OUT" SHOTS="$SHOTS" OPTIONS="$OPTIONS" python3 - "$EVAL" <<'PY'
import os, sys
v = lambda s: '@"' + s.replace('"', '""') + '"'
e = os.environ
open(sys.argv[1], "w").write("""// generated by tools/preview.sh
if (UnityEditor.EditorApplication.isPlayingOrWillChangePlaymode) throw new System.InvalidOperationException("Edit Mode only.");
var bytes = System.IO.File.ReadAllBytes(%s);
var pdbPath = %s;
var asm = System.IO.File.Exists(pdbPath) ? System.Reflection.Assembly.Load(bytes, System.IO.File.ReadAllBytes(pdbPath)) : System.Reflection.Assembly.Load(bytes);
var type = asm.GetType("TownLifePreview", true);
var run = type.GetMethod("Run", new[] { typeof(string), typeof(string), typeof(string), typeof(string) });
return (string)run.Invoke(null, new object[] { %s, %s, %s, %s });
""" % (v(e["DLL"]), v(e["PDB"]), v(e["MODULES"]), v(e["OUT"]), v(e["SHOTS"]), v(e["OPTIONS"])))
PY

# ---- 3. lock + editor gate
release() { if [ "$(cat "$LOCK/owner" 2>/dev/null)" = "$ME" ]; then rm -rf "$LOCK"; fi; }
status_ok() {
  unity command editor_status --project-path "$P" --json 2>/dev/null | python3 -c '
import json, sys
try: r = json.load(sys.stdin)["data"]["result"]
except Exception: sys.exit(1)
sys.exit(0 if r.get("playMode") == "stopped" and r.get("compiling") is False and not r.get("domainReloadInProgress") else 1)'
}
tries=0; waited=0
while true; do
  until mkdir "$LOCK" 2>/dev/null; do
    sleep 5; waited=$((waited+5))
    if [ $((waited % 120)) -eq 0 ]; then echo "preview.sh: waiting for editor.lock held by '$(cat "$LOCK/owner" 2>/dev/null)' for ${waited}s" >&2; fi
    if [ $waited -ge 1800 ]; then echo "preview.sh: gave up after 30 min waiting for editor.lock (owner '$(cat "$LOCK/owner" 2>/dev/null)'; possibly stale, NOT removed)" >&2; exit 4; fi
  done
  echo "$ME" > "$LOCK/owner"; trap release EXIT
  if status_ok || { sleep 3; status_ok; }; then break; fi          # one retry: transient "Network error" during a reload
  release; trap - EXIT
  tries=$((tries+1)); if [ $tries -ge 40 ]; then echo "preview.sh: editor stayed busy (play mode / compiling) for 20 min, giving up" >&2; exit 4; fi
  echo "preview.sh: editor busy (playing or compiling); released the lock, retrying in 30 s" >&2; sleep 30
done
T2=$(date +%s)

# ---- 4. run. The CLI may report a bogus main-thread timeout while the eval finishes: trust result.txt.
rm -f "$OUT/result.txt"
unity command eval_file --project-path "$P" --file "$EVAL" --timeout 600 --json > "$OUT/cli.txt" 2>&1
for i in $(seq 1 150); do [ -s "$OUT/result.txt" ] && break; sleep 2; done
release; trap - EXIT
T3=$(date +%s)

if [ ! -s "$OUT/result.txt" ]; then
  echo "preview.sh: NO result.txt after 300 s: the eval did not run or crashed before reporting. CLI said:" >&2
  head -c 3000 "$OUT/cli.txt" >&2; exit 1
fi
cat "$OUT/result.txt"
echo "preview.sh: compile $((T1-T0))s, wait-for-editor $((T2-T1))s, editor $((T3-T2))s, total $((T3-T0))s -> $OUT"
case "$(head -1 "$OUT/result.txt")" in OK) exit 0;; OK-WITH-MODULE-ERRORS) exit 3;; *) exit 1;; esac
